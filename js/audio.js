/* =====================================================================
   SE.Audio — sound effects + music (docs/SPEC.md §5.5).

   Files: assets/audio/sfx/<key>.mp3 (mono) and assets/audio/music/<key>.mp3
   (stereo, laid out [0.5 s pre-pad | loop | 0.5 s post-pad]); provenance in
   assets/audio/AUDIO-SOURCES.json; generated by tools/audio/build_audio.py.

   Engine
   - WebAudio for everything when available. SFX are decoded once by loadAll()
     (decodeAudioData of MP3). Music is decoded on demand into AudioBuffers and
     looped sample-accurately with loopStart/loopEnd (no gap at the seam); at
     most 3 decoded tracks are kept (2 on mobile, decoded at 32 kHz there to
     halve memory). Track changes cross-fade.
   - Without WebAudio: a small HTMLAudio pool for SFX and one HTMLAudio music
     element looped by hand (functional fallback, not gapless).
   - Silence rules: nothing is heard while paused (pause/resume, the game calls
     them for platform/ad/manual pauses) or while the platform disallows audio
     (setPlatformAudio(false), e.g. the YouTube mute) — the AudioContext is
     suspended then, so music time and fades freeze too. In-game toggles
     (setSfx/setMusic) never override a platform mute.
   - Autoplay: the context is resumed whenever sound is allowed; browsers that
     need a gesture get it from the first pointer/touch/key event (unlock()).
     SFX requested before the context runs are dropped (never queued), music is
     scheduled and starts the moment the context runs.
   - No visibilitychange/blur handling here (Playables forbids it; SE.Game
     calls pause()/resume()).

   Public API
     init(); unlock(); setPlatformAudio(bool)
     loadAll(onProgress(loaded,total)) -> Promise (never rejects)
     prepareMusic()                   start fetching/decoding the music
     play(name, opts) -> handle|null  opts: { volume=1, rate=1, vary (± semitones, random),
                                      pos:{x,z} (3D distance attenuation + stereo pan),
                                      range (max audible distance, default 120),
                                      loop (bool), delay (s), force (ignore the anti-spam gap) }
                                      handle: { stop(fadeSec), setVolume(v, fadeSec), name }
     stop(name, fadeSec)              stop every voice of a key
     step(speedFactor)                rate-limited random grass footstep
     setListener(x, z, yaw)           listener for pos attenuation; yaw = camera yaw where the
                                      camera looks along (sin yaw, cos yaw) in XZ (yaw π = north)
     playMusic(name, opts)            'base' | 'chase' | 'lair' | 'shop' (aliases: theme→base); cross-fades
                                      opts: { fade (s), restart (bool), intensity (chase start, 0.5) }
                                      musicName = the last track asked for here (the zone track)
     setMenuMusic(on, opts)           true while a menu panel (shop / wheel / daily …) is open: the calm
                                      'shop' track replaces base/lair (never chase) until set to false,
                                      then the zone track comes back where it left off (opts.fade, 0.7 s)
     currentMusic()                   the track that should be heard now (zone track or the menu override)
     stopMusic(fadeSec)
     setMusicIntensity(0..1)          chase track only: 0 = dragon far (−2.9 dB, highs −10 dB),
                                      1 = dragon close (full level, full brightness); e.g. call
                                      every frame with SE.DragonAI.threatLevel()
     fadeMusicTo(vol, ms)             duck/restore the music to an absolute volume (0..1,
                                      musicVolume = normal level)
     setSfx(on); setMusic(on); setVolumes(sfx, music)
     pause(); resume()
     randomRate(semitones, base)      helper: random playback-rate multiplier
     has(name); musicName (current/desired track); SFX_KEYS; MUSIC
   ===================================================================== */
