  const SHAPE = { sprite: 0, ring: 1, disc: 2, cone: 3, glow: 4, shock: 5 };
  let decals = [];
  function newDecal(o) {
    const d = Object.assign({
      x: 0, y: 0, z: 0, yaw: 0, age: 0, life: 1, size: 1, shape: SHAPE.ring, param: 0.2, frame: 0,
      billboard: false, fill: 0, progress: 0, alpha: 1, additive: false, color: new THREE.Color(1, 1, 1),
      anim: null, stopped: false, dead: false, fade: 0,
    }, o);
    decals.push(d);
    const h = {
      stop() { d.stopped = true; return h; },
      set(p) {
        if (!p) return h;
        if (p.x != null) d.x = p.x; if (p.y != null) d.y = p.y; if (p.z != null) d.z = p.z;
        if (p.yaw != null) d.yaw = p.yaw; if (p.radius != null) d.radius = p.radius; if (p.size != null) d.size = p.size;
        if (p.alpha != null) d.alpha = p.alpha; if (p.color != null) d.color = col(p.color);
        if (p.progress != null) d.fixedProgress = p.progress;
        return h;
      },
      get alive() { return !d.dead; },
      _d: d,
    };
    return h;
  }
  const easeOut = (t) => 1 - (1 - t) * (1 - t) * (1 - t);

  function ring(pos, opts) {
    ensure();
    const o = opts || {};
    const p = vecFrom(pos, new THREE.Vector3());
    const radius = o.radius == null ? 6 : o.radius;
    const from = o.from == null ? 0.12 : o.from;
    const alpha = o.alpha == null ? 0.9 : o.alpha;
    return newDecal({
      x: p.x, y: p.y + (o.y == null ? 0.06 : o.y), z: p.z, life: o.life || 0.6,
      shape: o.shock ? SHAPE.shock : SHAPE.ring, param: o.thickness == null ? (o.shock ? 0.45 : 0.2) : o.thickness,
      fill: o.fill || 0, additive: o.additive !== false, color: col(o.color || '#ffffff'), occlude: o.occlude == null ? 0.45 : o.occlude,
      anim(d) {
        const t = Math.min(1, d.age / d.life);
        d.size = 2 * radius * (from + (1 - from) * easeOut(t));
        d.a = alpha * (1 - t * t) * Math.min(1, t * 12 + 0.25);
      },
    });
  }

  function flash(pos, color, opts) {
    ensure();
    const o = opts || {};
    const p = vecFrom(pos, new THREE.Vector3());
    const size = o.size || 6, alpha = o.alpha == null ? 1 : o.alpha;
    return newDecal({
      x: p.x, y: p.y, z: p.z, life: o.life || 0.25, shape: SHAPE.glow, billboard: true, additive: true,
      color: col(color || o.color || '#fff4d0'), occlude: o.occlude == null ? 0.15 : o.occlude,
      anim(d) {
        const t = Math.min(1, d.age / d.life);
        d.size = size * (0.65 + 0.55 * easeOut(t));
        d.a = alpha * (1 - t) * (1 - t);
      },
    });
  }

  function telegraph(pos, opts) {
    ensure();
    const o = opts || {};
    const p = vecFrom(pos, new THREE.Vector3());
    const cone = o.shape === 'cone';
    const alpha = o.alpha == null ? 0.85 : o.alpha;
    const life = o.life || 0.9;
    return newDecal({
      x: p.x, y: (o.y != null ? o.y : p.y) + 0.07, z: p.z, life: life + 0.12, yaw: o.yaw || 0,
      radius: o.radius || (cone ? 18 : 4), shape: cone ? SHAPE.cone : SHAPE.disc,
      param: cone ? (o.angle != null ? o.angle : 35 * DEG) : 0.12, fill: o.fill == null ? 0.42 : o.fill,
      additive: !!o.additive, color: col(o.color || (cone ? '#2fa8ff' : '#ff2a1a')),
      anim(d) {
        const t = d.age;
        d.progress = d.fixedProgress != null ? d.fixedProgress : Math.min(1, t / life);
        d.size = 2 * d.radius * (t < 0.08 ? 0.6 + 0.4 * easeOut(t / 0.08) : 1);
        const pulse = 0.85 + 0.15 * Math.sin(t * 22);
        d.a = alpha * pulse * (t > life ? Math.max(0, 1 - (t - life) / 0.12) : Math.min(1, t / 0.06));
      },
    });
  }

  function decal(pos, opts) {
    ensure();
    const o = opts || {};
    const p = vecFrom(pos, new THREE.Vector3());
    const spr = o.sprite || 'ring';
    const shape = SHAPE[o.shape] != null ? SHAPE[o.shape] : SHAPE.sprite;
    const alpha = o.alpha == null ? 1 : o.alpha;
    return newDecal({
      x: p.x, y: p.y + (o.billboard ? 0 : 0.06), z: p.z, life: o.life == null ? Infinity : o.life, yaw: o.yaw || 0,
      size: o.size || 4, shape, param: o.param == null ? 0.2 : o.param, frame: FRAMES[spr] != null ? FRAMES[spr] : 0,
      billboard: !!o.billboard, additive: !!o.additive, color: col(o.color || '#ffffff'), fill: o.fill || 0,
      anim(d) {
        const t = d.age;
        const fadeIn = Math.min(1, t / 0.12);
        const fadeOut = d.life === Infinity ? 1 : Math.max(0, Math.min(1, (d.life - t) / 0.25));
        d.a = alpha * fadeIn * fadeOut;
      },
    });
  }

  function fireDecalLayer(e) {
    const L = e.layer;
    const sc = e.scale;
    const y = L.ground ? (e.groundY != null ? e.groundY : 0) : e.y + (L.offset[1] || 0) * sc;
    _v.set(e.x + (L.offset[0] || 0) * sc, y, e.z + (L.offset[2] || 0) * sc);
    const color = e.tint && L.tintable ? e.tint : L.color;
    if (L.type === 'ring') {
      ring(_v, { radius: (L.radius || 6) * sc, from: L.from, life: L.life, color, thickness: L.thickness, alpha: L.alpha, fill: L.fill, shock: L.shock, additive: L.additive, occlude: L.occlude });
    } else if (L.type === 'flash') {
      flash(_v, color, { size: (L.size || 6) * sc, life: L.life, alpha: L.alpha, occlude: L.occlude });
    }
  }

  function updateDecals(dt) {
    const sysA = D_ADD, sysN = D_NORM;
    let na = 0, nn = 0;
    const keep = [];
    for (let k = 0; k < decals.length; k++) {
      const d = decals[k];
      d.age += dt;
      if (d.stopped && !d.fadeStarted) { d.fadeStarted = true; d.fadeAt = d.age; }
      if (d.age >= d.life || (d.fadeStarted && d.age - d.fadeAt > 0.15)) { d.dead = true; continue; }
      d.a = 1;
      if (d.anim) d.anim(d);
      if (d.fadeStarted) d.a *= Math.max(0, 1 - (d.age - d.fadeAt) / 0.15);
      keep.push(d);
      const S = d.additive ? sysA : sysN;
      const i = d.additive ? na : nn;
      if (i >= DECAL_CAP) continue;
      if (d.additive) na++; else nn++;
      const A = S.attrs;
      A.iPos.array[i * 3] = d.x; A.iPos.array[i * 3 + 1] = d.y; A.iPos.array[i * 3 + 2] = d.z;
      A.iA.array[i * 4] = d.size; A.iA.array[i * 4 + 1] = -d.yaw; A.iA.array[i * 4 + 2] = d.shape; A.iA.array[i * 4 + 3] = d.param;
      A.iC.array[i * 4] = d.color.r; A.iC.array[i * 4 + 1] = d.color.g; A.iC.array[i * 4 + 2] = d.color.b; A.iC.array[i * 4 + 3] = d.a * (d.alphaMul == null ? 1 : d.alphaMul);
      A.iB.array[i * 4] = d.frame; A.iB.array[i * 4 + 1] = (d.billboard ? -1 : 1) * (1 + (d.occlude == null ? 0.3 : d.occlude)); A.iB.array[i * 4 + 2] = d.fill; A.iB.array[i * 4 + 3] = d.progress;
    }
    decals = keep;
    [[sysA, na], [sysN, nn]].forEach(([S, n]) => {
      S.geo.instanceCount = n;
      Object.keys(S.attrs).forEach((key) => { S.attrs[key].needsUpdate = true; });
    });
  }

  /* ------------------------------------------------------------------ public */
  function init(sc, q) {
    ensure();
    if (scene && scene !== sc) [P_ADD, P_NORM, D_ADD, D_NORM].forEach((s) => scene.remove(s.obj));
    scene = sc;
    if (scene) [D_NORM, D_ADD, P_NORM, P_ADD].forEach((s) => { if (s.obj.parent !== scene) scene.add(s.obj); });
    setQuality(q || quality);
    return api;
  }

  function setQuality(q) {
    if (q === 'auto' || !QUALITY[q]) q = (SE.Platform && SE.Platform.isMobile) ? 'low' : 'high';
    quality = q;
    return api;
  }

  function update(dt) {
    if (!P_ADD) return;
    dt = Math.min(Math.max(dt || 0, 0), 0.1);
    frameId++;
    for (let k = 0; k < emitters.length; k++) updateEmitter(emitters[k], dt);
    if (emitters.some((e) => e.dead)) emitters = emitters.filter((e) => !e.dead);
    updateSystem(P_ADD, dt);
    updateSystem(P_NORM, dt);
    updateDecals(dt);
  }

  function clear() {
    if (!P_ADD) return;
    emitters.forEach((e) => { e.dead = true; e.stopped = true; });
    emitters = [];
    decals.forEach((d) => { d.dead = true; });
    decals = [];
    [P_ADD, P_NORM].forEach((s) => {
      for (let i = 0; i < s.n; i++) { s.layer[i] = null; s.em[i] = null; }
      s.n = 0; s.geo.setDrawRange(0, 0);
    });
    [D_ADD, D_NORM].forEach((d) => { d.geo.instanceCount = 0; });
  }

  function emit(name, pos, opts) {
    ensure();
    const R = getRecipe(name);
    if (!R) { if (!warned[name]) { warned[name] = true; console.warn('SE.FX: unknown recipe "' + name + '"'); } return makeHandle([]); }
    const p = vecFrom(pos, new THREE.Vector3());
    const list = R.layers.map((L) => newEmitter(L, R, p, null, opts));
    list.forEach((e) => { emitters.push(e); if (!e.delay && !(opts && opts.defer)) updateEmitter(e, 0); });
    return makeHandle(list);
  }
  const warned = {};

  function attach(name, object3D, opts) {
    ensure();
    const R = getRecipe(name);
    if (!R || !object3D) { if (!R && !warned[name]) { warned[name] = true; console.warn('SE.FX: unknown recipe "' + name + '"'); } return makeHandle([]); }
    const list = R.layers.map((L) => newEmitter(L, R, null, object3D, opts));
    list.forEach((e) => emitters.push(e));
    return makeHandle(list);
  }

  function stats() {
    return {
      particles: liveCount(), add: P_ADD ? P_ADD.n : 0, normal: P_NORM ? P_NORM.n : 0,
      emitters: emitters.length, decals: decals.length, budget: budget(), quality,
      drawCalls: P_ADD ? (P_ADD.n > 0) + (P_NORM.n > 0) + (D_ADD.geo.instanceCount > 0) + (D_NORM.geo.instanceCount > 0) : 0,
    };
  }

