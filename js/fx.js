  let atlasTex = null;
  let readyResolve;
  const ready = new Promise((r) => { readyResolve = r; });
  function fallbackAtlas() {
    const cv = document.createElement('canvas');
    cv.width = GRID_X * 64; cv.height = GRID_Y * 64;
    const g = cv.getContext('2d');
    for (let i = 0; i < GRID_X * GRID_Y; i++) {
      const x = (i % GRID_X) * 64 + 32, y = Math.floor(i / GRID_X) * 64 + 32;
      const gr = g.createRadialGradient(x, y, 0, x, y, 30);
      gr.addColorStop(0, 'rgba(255,255,255,1)');
      gr.addColorStop(i === 0 ? 0.0 : 0.55, 'rgba(255,255,255,' + (i === 0 ? 1 : 0.95) + ')');
      gr.addColorStop(1, 'rgba(255,255,255,0)');
      g.fillStyle = gr;
      g.fillRect(x - 32, y - 32, 64, 64);
    }
    return cv;
  }
  function getAtlas() {
    if (atlasTex) return atlasTex;
    atlasTex = new THREE.Texture();
    atlasTex.flipY = false;
    atlasTex.generateMipmaps = true;
    atlasTex.minFilter = THREE.LinearMipmapLinearFilter;
    atlasTex.magFilter = THREE.LinearFilter;
    const img = new Image();
    img.onload = () => { atlasTex.image = img; atlasTex.needsUpdate = true; readyResolve(true); };
    img.onerror = () => {
      console.warn('SE.FX: atlas.png failed to load — using a soft-dot fallback atlas');
      atlasTex.image = fallbackAtlas(); atlasTex.needsUpdate = true; readyResolve(false);
    };
    img.src = (SE.Assets && SE.Assets.resolveUrl ? SE.Assets.resolveUrl('assets/fx/atlas.png') : baseUrl + 'assets/fx/atlas.png');
    return atlasTex;
  }

