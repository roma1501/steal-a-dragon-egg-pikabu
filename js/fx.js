/* =========================================================================
   Steal a Dragon Egg — particles & effects (SE.FX)            SPEC §7

   GPU-friendly pooled particles. Everything is drawn with at most 4 draw calls:
     1. THREE.Points, additive blending      (sparkles, fire, glows …)
     2. THREE.Points, normal blending        (smoke, leaves, coins, confetti …)
     3. instanced quads, normal blending     (ground telegraphs / decals)
     4. instanced quads, additive blending   (shockwave rings, flashes)
   Particles read ONE sprite atlas (assets/fx/atlas.png, 8×4 cells, generated by
   tools/fx/make-sprites.py; white masks tinted per particle). Point sprites are
   sized in world units (perspective attenuation), rotate, can be velocity-aligned,
   fade with the scene fog and use the renderer's tone mapping / output encoding.

   API
     SE.FX.init(scene, quality)           quality 'high' | 'medium' | 'low' | 'auto' (auto: mobile → low)
     SE.FX.setQuality(q)                  budget high 1500 / medium 1050 / low 600 live particles;
                                          spawn counts & rates × 1 / 0.75 / 0.5
     SE.FX.update(dt)                     simulate (call once per frame; skip while paused)
     SE.FX.clear()                        kill every particle, emitter and decal (nothing leaks)
     SE.FX.register(name, recipe)         add / replace a recipe (see RECIPE FORMAT)
     SE.FX.emit(name, pos, opts) -> handle
     SE.FX.attach(name, object3D, opts) -> handle   emitter follows the object (world matrix)
         handle = { stop(), setRate(k), setPosition(v), alive }   (stop: no new particles, live ones finish)
         opts   = { scale:1 (size, spread, speed), count:1 (burst ×), rate:1 (rate ×), color:'#hex' (tints
                    layers marked tintable), dir:Vector3|[x,y,z] (cone direction), duration (s, rate layers;
                    attach default ∞, emit default from the recipe), delay (s), groundY (ring/ground layers),
                    width / size:[x,y,z] (box shapes, e.g. safe_line_glow width), yaw (rotates shapes & dirs),
                    offset:Vector3|[x,y,z] (attach, object-local), orient:true (attach: dirs follow the
                    object's rotation, e.g. breath from rig.mouth), local:true (particles move with the object),
                    cull: metres (attach: no spawning farther than this from the camera, default 170) }
     SE.FX.ring(pos, opts) -> handle      expanding ground ring / shockwave
         { radius:6, from:0.12 (start fraction), life:0.6, color, thickness:0.2, alpha:0.9, fill:0,
           additive:true, y:0.06, shock:false (soft trailing wave) }
     SE.FX.flash(pos, color, opts) -> handle   short additive camera-facing glow { size:6, life:0.25, alpha:1 }
     SE.FX.telegraph(pos, opts) -> handle      ground warning that fills up until it fires
         { shape:'disc'|'cone', radius:4, angle (cone half-angle, rad, default 35°), yaw (cone facing,
           same convention as Object3D.rotation.y), life:0.9, color:'#ff3b2a', alpha:0.85, fill:0.28 }
         handle.set({ x, z, y, yaw, radius }) moves it; progress = age / life
     SE.FX.decal(pos, opts) -> handle     persistent decal { sprite:'ring'|frame name, size, color, alpha, yaw,
                                          billboard:false, additive:false, life:Infinity }
     SE.FX.has(name); SE.FX.recipes (names); SE.FX.RECIPES (definitions); SE.FX.FRAMES
     SE.FX.stats() -> { particles, add, normal, emitters, decals, budget, quality, drawCalls }
     SE.FX.seed(n|null)                   deterministic random numbers (QA screenshots); null = Math.random
     SE.FX.setBudget(n|null)              override the live-particle budget (labs)
     SE.FX.ready -> Promise               resolves when the atlas texture is loaded (or its fallback is built)

   RECIPE FORMAT  { layers:[ layer, … ], duration? }
     particle layer: { blend:'add'|'normal', sprite:'soft'|[names], burst:n|[a,b], rate:n/s, duration:s,
       delay:s, stagger:s (spread the burst over time), life:[a,b], offset:[x,y,z],
       shape:{ type:'point'|'sphere'|'hemi'|'disc'|'ring'|'box'|'line', radius, inner, size:[x,y,z], y:[a,b], surface },
       speed:[a,b] (along dir±spread° if dir is set, else radial from the shape), dir:[x,y,z], spread:deg,
       vel:[x,y,z] (added), jitter:[x,y,z] (± random), gravity (down +), drag, swirl (rad/s about the
       emitter's vertical axis), curl, curlFreq (sinusoidal turbulence), size:n|[curve]|[[t,v]…], sizeRand:[a,b],
       alpha:[curve] (default [1,0]), color:'#hex'|[gradient], palette:[colours per particle], rainbow:true,
       spin:[a,b] rad/s, rot:'random'|n|[a,b], align:true (velocity aligned), flicker:0..1, flickerFreq,
       floor:dy (collide with y = origin + dy), bounce, wrap:[hx,hy,hz] (ambient volume around the
       anchor), local, ambient (lower priority, first to be dropped), tintable, inherit (anchor velocity),
       orient (dir follows the anchor), ground (spawn at groundY), sub:{ name, chance } (on death) }
     ring layer:  { type:'ring', radius, from, life, color, thickness, alpha, fill, delay, ground, shock, additive }
     flash layer: { type:'flash', size, life, color, alpha, delay, offset }
   Curves: number, [a, b, …] (evenly spaced keys) or [[t, v], …]. Colours are sRGB hex strings.

   Scale reference: player ≈ 7 u tall, adult dragon ≈ 26 u long, camera 12–60 u away.
   Recipes: dust steal_burst hatch_burst coin_burst gem_burst roar_wave zzz fireball_trail fireball_hit
   frost_breath freeze_hit dash_leaves dash_sand sparkle gold_glints crystal_glints rainbow_motes
   galaxy_stars confetti unlock_burst levelup amb_leaves amb_fireflies amb_sand amb_snow amb_embers
   amb_stars safe_line_glow  (+ extras: poof, stun_stars, hearts, notes, splash_dust)
   ========================================================================= */
