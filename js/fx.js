  /* ------------------------------------------------------------------ curves */
  function keysOf(spec) {
    if (Array.isArray(spec) && spec.length && Array.isArray(spec[0])) return spec;
    if (Array.isArray(spec)) return spec.map((v, i) => [spec.length === 1 ? 0 : i / (spec.length - 1), v]);
    return [[0, spec]];
  }
  function sampleKeys(keys, t, lerp) {
    if (t <= keys[0][0]) return keys[0][1];
    for (let i = 1; i < keys.length; i++) {
      if (t <= keys[i][0]) {
        const a = keys[i - 1], b = keys[i];
        const f = (t - a[0]) / Math.max(1e-6, b[0] - a[0]);
        return lerp(a[1], b[1], f);
      }
    }
    return keys[keys.length - 1][1];
  }
  const lerpN = (a, b, f) => a + (b - a) * f;
  function numLUT(spec, def) {
    const out = new Float32Array(LUT);
    if (spec == null) spec = def;
    if (typeof spec === 'number') { out.fill(spec); return out; }
    const keys = keysOf(spec);
    for (let i = 0; i < LUT; i++) out[i] = sampleKeys(keys, i / (LUT - 1), lerpN);
    return out;
  }
  const _ca = new THREE.Color(), _cb = new THREE.Color();
  function col(c) { return c instanceof THREE.Color ? c.clone() : new THREE.Color(c == null ? '#ffffff' : c); }
  function colorLUT(spec) {
    const out = new Float32Array(LUT * 3);
    if (spec == null) spec = '#ffffff';
    const keys = keysOf(typeof spec === 'string' || typeof spec === 'number' ? [spec] : spec).map((k) => [k[0], col(k[1])]);
    for (let i = 0; i < LUT; i++) {
      const c = sampleKeys(keys, i / (LUT - 1), (a, b, f) => _ca.copy(a).lerp(b, f));
      const cc = c.isColor ? c : _ca.copy(c);
      out[i * 3] = cc.r; out[i * 3 + 1] = cc.g; out[i * 3 + 2] = cc.b;
    }
    return out;
  }

  /* ------------------------------------------------------------------ recipes */
